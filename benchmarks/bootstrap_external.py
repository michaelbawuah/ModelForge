"""Create a reproducible external-runtime deployment for benchmarks."""

from __future__ import annotations

import argparse
import json
import uuid

import httpx


def bootstrap_external_runtime(
    *,
    base_url: str,
    environment: str,
    timeout_seconds: float,
) -> dict[str, object]:
    """Register and promote a unique go-linear benchmark deployment."""

    suffix = uuid.uuid4().hex[:10]

    with httpx.Client(
        base_url=base_url.rstrip("/"),
        timeout=timeout_seconds,
    ) as client:
        model_response = client.post(
            "/models",
            json={
                "name": f"benchmark-go-linear-{suffix}",
                "description": "Generated by ModelForge benchmark bootstrap.",
            },
        )
        model_response.raise_for_status()
        model = model_response.json()

        version_response = client.post(
            f"/models/{model['id']}/versions",
            json={
                "version": "1.0.0",
                "framework": "go-linear",
                "artifact_uri": f"external://go-linear/{suffix}",
                "checksum": f"benchmark-{suffix}",
            },
        )
        version_response.raise_for_status()
        version = version_response.json()

        deployment_response = client.post(
            "/deployments",
            json={
                "model_version_id": version["id"],
                "environment": environment,
            },
        )
        deployment_response.raise_for_status()
        deployment = deployment_response.json()

        promotion_response = client.post(
            f"/deployments/{deployment['id']}/promote"
        )
        promotion_response.raise_for_status()
        promoted = promotion_response.json()

    return {
        "environment": environment,
        "model_id": model["id"],
        "model_version_id": version["id"],
        "deployment_id": promoted["id"],
        "framework": version["framework"],
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--environment", default="benchmark-go")
    parser.add_argument("--timeout-seconds", type=float, default=10.0)
    parser.add_argument("--output")
    args = parser.parse_args()

    result = bootstrap_external_runtime(
        base_url=args.base_url,
        environment=args.environment,
        timeout_seconds=args.timeout_seconds,
    )

    payload = json.dumps(result, indent=2, sort_keys=True)
    print(payload)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as output_file:
            output_file.write(payload)
            output_file.write("\n")


if __name__ == "__main__":
    main()
